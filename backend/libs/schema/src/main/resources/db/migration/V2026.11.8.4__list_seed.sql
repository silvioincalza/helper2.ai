CREATE TABLE list_seed (
    repository text        PRIMARY KEY CHECK (repository ~ '^[a-z0-9-]{1,39}/[a-z0-9._-]{1,100}$'),
    added_by   text        NOT NULL,
    added_at   timestamptz NOT NULL,
    reason     text        CHECK (reason IS NULL OR length(reason) <= 500)
);

