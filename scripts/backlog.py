class Answer:
    def __init__(self, done):
        head, _, body = done.stdout.replace("\r\n", "\n").partition("\n\n")
        pairs = (line.partition(":") for line in head.split("\n")[1:])
        self.passed = done.returncode == 0
        self.unavailable = bool(re.match(r"HTTP/\S+ 5\d\d", head))
        self.headers = {name.strip().lower(): value.strip() for name, _, value in pairs}
        self.body = GhCli.parsed(body)
        self.error = f"{done.stderr.strip()}\n{body.strip()}".strip()

    @property
    def paused(self) -> bool:
        return "retry-after" in self.headers or "secondary" in self.error.lower()

    @property
    def out_of_budget(self) -> bool:
        return self.headers.get("x-ratelimit-remaining") == "0" or "rate limit" in self.error.lower()


class GhCli:
    def __init__(self, write: bool = False, pause: float = 1.0, backoff: float = 60.0):
        self.write = write
        self.pause = pause
        self.backoff = backoff
        self.commands = 0
        self.budget: dict = {}
        self.read: dict[str, list[dict]] = {}
        self.now = time.time
        self.sleep = time.sleep

    def run(self, args: list[str], data: str | None = None):
        for attempt in range(1, GH_ATTEMPTS + 1):
            done = self.gh(args, data)
            if done.returncode == 0:
                return self.parsed(done.stdout)
            if not self.throttled(done.stderr):
                sys.exit(f"gh {' '.join(args[:4])} failed:\n{done.stderr}")
            if attempt < GH_ATTEMPTS:
                self.graphql(BUDGET_QUERY)
                self.wait(self.backoff * attempt)
        sys.exit(f"gh {' '.join(args[:4])} was throttled {GH_ATTEMPTS} times, stop:\n{done.stderr}")

    def api(self, args: list[str], data: str | None = None):
        for attempt in range(1, GH_ATTEMPTS + 1):
            answer = Answer(self.gh(["api", "-i", *args], data))
            self.note_budget(answer.headers)
            if answer.passed:
                return answer.body
            if not (answer.paused or answer.out_of_budget or answer.unavailable):
                sys.exit(f"gh api {' '.join(args[:3])} failed:\n{answer.error}")
            if attempt < GH_ATTEMPTS:
                self.hold(answer, attempt)
        sys.exit(f"gh api {' '.join(args[:3])} was throttled {GH_ATTEMPTS} times, stop:\n{answer.error}")

    def gh(self, args: list[str], data: str | None):
        self.commands += 1
        return subprocess.run(["gh", *args], input=data, capture_output=True, text=True)

    def note_budget(self, headers: dict[str, str]) -> None:
        if headers.get("x-ratelimit-resource") == "graphql" and "x-ratelimit-reset" in headers:
            self.budget = {"left": int(headers["x-ratelimit-remaining"]), "reset": float(headers["x-ratelimit-reset"])}

    def hold(self, answer: Answer, attempt: int) -> None:
        if answer.paused:
            self.wait(float(answer.headers.get("retry-after", self.backoff * attempt)))
            return
        if answer.unavailable:
            self.wait(SERVER_ERROR_WAIT * attempt, "GitHub failed to serve the command")
            return
        reset = answer.headers.get("x-ratelimit-reset")
        if not reset:
            sys.exit(f"GitHub's hourly limit is used up and GitHub does not say until when, stop:\n{answer.error}")
        seconds = max(float(reset) - self.now(), 0) + RESET_MARGIN
        if seconds > SHORT_WAIT:
            sys.exit(
                f"GitHub's hourly limit is used up until {clock(float(reset))}: run again after that. "
                "What is written stays written, the next run writes the rest"
            )
        print(f"  GitHub's hourly limit is used up, waiting {seconds:.0f}s until {clock(float(reset))}")
        self.sleep(seconds)

    @staticmethod
    def throttled(error: str) -> bool:
        return any(sign in error.lower() for sign in THROTTLED)

    def wait(self, seconds: float, why: str = "GitHub throttled the command") -> None:
        print(f"  {why}, waiting {seconds:.0f}s")
        self.sleep(seconds)

    @staticmethod
    def parsed(out: str):
        if not out.strip():
            return {}
        try:
            return json.loads(out)
        except json.JSONDecodeError:
            return out

    def change(self, what: str, args: list[str], data: str | None = None):
        if not self.write:
            print(f"  would {what}")
            return None
        print(f"  {what}")
        result = self.api(args[1:], data) if args[0] == "api" else self.run(args, data)
        self.sleep(self.pause)
        return result

    def graphql(self, query: str, **variables) -> dict:
        return self.api(["graphql", "--input", "-"], json.dumps({"query": query, "variables": variables}))["data"]

    def pages(self, query: str, connection, **variables) -> list[dict]:
        nodes: list[dict] = []
        cursor = None
        while True:
            page = connection(self.graphql(query, endCursor=cursor, **variables))
            nodes += page["nodes"]
            if not page["pageInfo"]["hasNextPage"]:
                return nodes
            cursor = page["pageInfo"]["endCursor"]

    def repo_issues(self, query: str, repo: str) -> list[dict]:
        owner, name = repo.split("/")
        return self.pages(query, lambda data: data["repository"]["issues"], owner=owner, name=name)

    def mutate(self, changes: list[tuple[str, str]], size: int = MUTATIONS_PER_REQUEST) -> list[dict]:
        if not self.write:
            for what, _ in changes:
                print(f"  would {what}")
            return []
        self.require_budget(len(changes), size)
        results: list[dict] = []
        for start in range(0, len(changes), size):
            batch = changes[start : start + size]
            for what, _ in batch:
                print(f"  {what}")
            sent = self.graphql("mutation{" + " ".join(f"m{n}:{mutation}" for n, (_, mutation) in enumerate(batch)) + "}")
            results += [sent[f"m{n}"] for n in range(len(batch))]
            print(f"  written: {len(results)} of {len(changes)}")
            self.sleep(self.pause)
        return results

    def require_budget(self, changes: int, size: int) -> None:
        needed = -(-changes // size) * POINTS_PER_REQUEST
        if self.budget and needed > self.budget["left"]:
            sys.exit(
                f"this run needs about {needed} points of GitHub's hourly limit and {self.budget['left']} are left "
                f"until {clock(self.budget['reset'])}: run again after that. Nothing of this step was written"
            )

    def report(self) -> None:
        left = f", {self.budget['left']} points left until {clock(self.budget['reset'])}" if self.budget else ""
        print(f"GitHub: {self.commands} gh commands{left}")

