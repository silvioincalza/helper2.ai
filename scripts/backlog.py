def exits(action) -> bool:
    try:
        action()
    except SystemExit as stop:
        return bool(stop.code)
    return False


def checked(pull: dict, issues: list[dict]) -> list[str]:
    with redirect_stdout(io.StringIO()):
        return pr_stories(pull, issues)


def dry_run_writes_nothing() -> bool:
    ran: list[list[str]] = []

    class Recording(GhCli):
        def run(self, args, data=None):
            ran.append(args)
            return {"projects": []} if args[:2] == ["project", "list"] else []

    out = io.StringIO()
    with redirect_stdout(out):
        Import(SAMPLE, Recording(write=False)).run()
    reads = [["api", "--paginate"], ["api", "graphql"], ["project", "list"]]
    return all(args[:2] in reads for args in ran) and out.getvalue().count("would create the issue") == 7


def main() -> None:
    parser = argparse.ArgumentParser(description="The backlog of this repository: GitHub issues and a GitHub Project.")
    parser.add_argument("--self-test", action="store_true", help="run the tests of this script, without network")
    commands = parser.add_subparsers(dest="command")
    importer = commands.add_parser("import", help="create or update the issues and the Project from a backlog file")
    importer.add_argument("file")
    importer.add_argument("--write", action="store_true", help="write to GitHub; without it the run only prints")
    importer.add_argument("--pause", type=float, default=1.0, help="seconds to wait after each write")
    importer.set_defaults(run=command_import)
    page = commands.add_parser("roadmap", help="write docs/roadmap.md from the open issues")
    page.add_argument("--repo", help="owner/name; the repository of this checkout when absent")
    page.add_argument("--output", default=None)
    page.set_defaults(run=command_roadmap)
    check = commands.add_parser("pr-stories", help="prove a replay pull request closes the stories of its slice only")
    check.add_argument("pull_request")
    check.add_argument("--repo", help="owner/name; the repository of this checkout when absent")
    check.set_defaults(run=command_pr_stories)
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return
    if not args.command:
        parser.error("a command is required: import, roadmap or pr-stories")
    if args.command == "roadmap" and args.output is None:
        root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True)
        args.output = os.path.join(root.stdout.strip(), ROADMAP_PAGE)
    args.run(args)


if __name__ == "__main__":
    main()
