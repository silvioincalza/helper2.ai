def throttled_command_is_tried_again() -> bool:
    budget = replied({"data": {"rateLimit": {"remaining": 4000}}})
    throttled = Scripted(
        [failed("unknown owner type"), budget, failed("API rate limit exceeded"), budget, replied({"id": "P1"})]
    )
    throttled.answers[-1] = subprocess.CompletedProcess([], 0, '{"id": "P1"}', "")
    broken = Scripted([failed("could not resolve to a ProjectV2")])
    endless = Scripted([failed("unknown owner type"), budget] * GH_ATTEMPTS)
    read = quiet(lambda: throttled.run(["project", "create"]))
    stopped = stop_of(lambda: broken.run(["project", "create"]))
    gave_up = stop_of(lambda: endless.run(["project", "create"]))
    tried = [args for args, _ in endless.sent if args[0] == "project"]
    return read == {"id": "P1"} and bool(stopped) and broken.commands == 1 and bool(gave_up) and len(tried) == GH_ATTEMPTS


def throttled_command_stops_without_budget() -> bool:
    github = Scripted([failed("unknown owner type"), used_up(NOON + 1800)])
    stopped = stop_of(lambda: github.run(["project", "create"]))
    return f"used up until {clock(NOON + 1800)}: run again after that" in stopped and github.commands == 2


def page_of(nodes: list[dict], cursor: str | None):
    return {"pageInfo": {"hasNextPage": cursor is not None, "endCursor": cursor}, "nodes": nodes}


def reads_are_paged() -> bool:
    def item(number: int, values: list[dict]) -> dict:
        return {"id": f"I{number}", "content": {"url": f"https://example.test/{number}"}, "fieldValues": {"nodes": values}}

    def listed(number: int, **more) -> dict:
        issue = {"number": number, "id": number, "node_id": f"N{number}", "html_url": "u", "title": "t"}
        return issue | {"author_association": "OWNER"} | more

    def named(field: str, **value) -> dict:
        return {**value, "field": {"name": field}}

    first = [item(1, [named("Priority", name="Now"), named("Title", text="One"), {}]), {"id": "I9", "content": {}}]
    second = [item(2, [named("Release", text="2026.11.3"), named("Replay PR", number=3.0)])]
    github = Scripted(
        [
            replied({"data": {"node": {"items": page_of(first, "c1")}}}),
            replied({"data": {"node": {"items": page_of(second, None)}}}),
            replied([listed(number) for number in range(PAGE)]),
            replied([listed(PAGE, pull_request={})]),
        ]
    )
    items = github.items({"id": "P1"}, ["Priority", "Release", "Replay PR"])
    issues = github.issues("example/shop")
    return (
        items
        == {
            "https://example.test/1": {"id": "I1", "values": {"Priority": "Now", "Release": None, "Replay PR": None}},
            "https://example.test/2": {"id": "I2", "values": {"Priority": None, "Release": "2026.11.3", "Replay PR": 3.0}},
        }
        and json.loads(github.sent[1][1])["variables"] == {"endCursor": "c1", "project": "P1"}
        and len(issues) == PAGE
        and github.sent[3][0][-1].endswith("&page=2")
        and github.commands == 4
    )


