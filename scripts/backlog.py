class GhCli:
    def __init__(self, write: bool = False, pause: float = 1.0):
        self.write = write
        self.pause = pause

    def run(self, args: list[str], data: str | None = None):
        for attempt in range(5):
            done = subprocess.run(["gh", *args], input=data, capture_output=True, text=True)
            if done.returncode == 0:
                return self.parsed(done.stdout)
            if "rate limit" not in done.stderr.lower() and "secondary" not in done.stderr.lower():
                sys.exit(f"gh {' '.join(args[:4])} failed:\n{done.stderr}")
            wait = 60 * (attempt + 1)
            print(f"  rate limited, waiting {wait}s")
            time.sleep(wait)
        sys.exit("rate limited five times, stop")

    @staticmethod
    def parsed(out: str):
        if not out.strip():
            return {}
        try:
            return json.loads(out)
        except json.JSONDecodeError:
            return out

    def change(self, what: str, args: list[str], data: str | None = None):
        if not self.write:
            print(f"  would {what}")
            return None
        result = self.run(args, data)
        time.sleep(self.pause)
        return result

    def graphql(self, query: str, repo: str) -> list[dict]:
        owner, name = repo.split("/")
        pages = self.run(
            ["api", "graphql", "--paginate", "--slurp", "-f", f"query={query}", "-F", f"owner={owner}", "-F", f"name={name}"]
        )
        return [node for page in pages for node in page["data"]["repository"]["issues"]["nodes"]]

    def current_repo(self) -> str:
        return self.run(["repo", "view", "--json", "nameWithOwner"])["nameWithOwner"]

    def tracked_issues(self, repo: str, states: str) -> list[dict]:
        return [tracked(node) for node in self.graphql(ISSUES_QUERY.replace("STATES", states), repo)]

    def pull_request(self, repo: str, number: str) -> dict:
        view = self.run(
            ["pr", "view", number, "--repo", repo, "--json", "headRefName,closingIssuesReferences,title,body"]
        )
        return {
            "branch": view["headRefName"],
            "title": view["title"],
            "body": view["body"],
            "closes": [issue["number"] for issue in view["closingIssuesReferences"]],
        }

    def ensure_label(self, repo: str, name: str, color: str) -> None:
        self.change(f"keep the label {name}", ["label", "create", name, "--repo", repo, "--color", color, "--force"])

    def issues(self, repo: str) -> list[dict]:
        pages = self.run(["api", "--paginate", "--slurp", f"repos/{repo}/issues?state=all&per_page=100"])
        return [
            {"number": i["number"], "id": i["id"], "url": i["html_url"], "title": i["title"], "body": i.get("body") or ""}
            for page in pages
            for i in page
            if "pull_request" not in i
        ]

    def create_issue(self, repo: str, title: str, body: str, label: str) -> dict | None:
        payload = json.dumps({"title": title, "body": body, "labels": [label]})
        made = self.change(f"create the issue {title}", ["api", "-X", "POST", f"repos/{repo}/issues", "--input", "-"], payload)
        return made and {"number": made["number"], "id": made["id"], "url": made["html_url"], "title": title, "body": body}

    def update_issue(self, repo: str, number: int, title: str, body: str, label: str) -> None:
        payload = json.dumps({"title": title, "body": body, "labels": [label]})
        self.change(
            f"update the issue #{number} {title}",
            ["api", "-X", "PATCH", f"repos/{repo}/issues/{number}", "--input", "-"],
            payload,
        )

    def parents(self, repo: str) -> dict[int, int | None]:
        return {n["number"]: (n["parent"] or {}).get("number") for n in self.graphql(PARENTS_QUERY, repo)}

    def add_sub_issue(self, repo: str, parent: int, child: dict) -> None:
        self.change(
            f"put #{child['number']} under #{parent}",
            ["api", "-X", "POST", f"repos/{repo}/issues/{parent}/sub_issues", "-F", f"sub_issue_id={child['id']}"],
        )

    def project(self, owner: str, title: str) -> dict | None:
        listed = self.run(["project", "list", "--owner", owner, "--format", "json", "--limit", "100"])
        found = next((p for p in listed.get("projects", []) if p["title"] == title), None)
        return found and {"number": str(found["number"]), "id": found["id"], "owner": owner}

    def create_project(self, owner: str, title: str) -> dict | None:
        made = self.change(
            f"create the Project {title}", ["project", "create", "--owner", owner, "--title", title, "--format", "json"]
        )
        return made and {"number": str(made["number"]), "id": made["id"], "owner": owner}

    def link_project(self, project: dict, repo: str) -> None:
        self.change(
            f"link the Project to {repo}",
            ["project", "link", project["number"], "--owner", project["owner"], "--repo", repo],
        )

    def fields(self, project: dict) -> dict[str, dict]:
        listed = self.run(
            ["project", "field-list", project["number"], "--owner", project["owner"], "--format", "json", "--limit", "50"]
        )
        return {
            f["name"]: {"id": f["id"], "options": {o["name"]: o["id"] for o in f.get("options", [])}}
            for f in listed["fields"]
        }

    def create_field(self, project: dict, name: str, kind: str, options: list[str]) -> None:
        args = ["project", "field-create", project["number"], "--owner", project["owner"], "--name", name, "--data-type", kind]
        if options:
            args += ["--single-select-options", ",".join(options)]
        self.change(f"create the field {name}", args)

    def items(self, project: dict, names: list[str]) -> dict[int, dict]:
        listed = self.run(
            ["project", "item-list", project["number"], "--owner", project["owner"], "--format", "json", "--limit", "5000"]
        )
        return {
            item["content"]["number"]: {"id": item["id"], "values": {n: self.value(item, n) for n in names}}
            for item in listed.get("items", [])
            if item.get("content", {}).get("number")
        }

    @staticmethod
    def value(item: dict, name: str):
        return item.get(name[0].lower() + name[1:], item.get(name.lower()))

    def add_item(self, project: dict, issue: dict) -> dict | None:
        made = self.change(
            f"add #{issue['number']} to the Project",
            ["project", "item-add", project["number"], "--owner", project["owner"], "--url", issue["url"], "--format", "json"],
        )
        return made and {"id": made["id"], "values": {}}

    def set_field(self, project: dict, item: dict | None, issue: dict, name: str, field: dict, value) -> None:
        args = ["project", "item-edit", "--id", (item or {}).get("id", ""), "--project-id", project["id"], "--field-id", field["id"]]
        if field["options"]:
            args += ["--single-select-option-id", field["options"][value]]
        elif isinstance(value, (int, float)):
            args += ["--number", str(value)]
        else:
            args += ["--text", value]
        self.change(f"set {name} of #{issue['number']} to {value}", args)


def tracked(node: dict) -> dict:
    items = node["projectItems"]["nodes"]
    parent = node.get("parent") or {}
    return {
        "number": node["number"],
        "title": node["title"],
        "url": node["url"],
        "labels": [label["name"] for label in node["labels"]["nodes"]],
        "epic": (parent.get("parent") or parent).get("title"),
        "priority": next((i["priority"]["name"] for i in items if i.get("priority")), None),
        "replay": next((int(i["replay"]["number"]) for i in items if i.get("replay")), None),
    }


def natural(text: str) -> list:
    return [int(part) if part.isdigit() else part for part in re.split(r"(\d+)", text)]


def entries(doc: dict) -> list[dict]:
    return doc["epics"] + doc["features"] + doc["stories"] + doc.get("tasks", [])


def problems(doc: dict) -> list[str]:
    ids = [x["id"] for x in entries(doc)]
    twice = sorted({i for i in ids if ids.count(i) > 1})
    orphans = sorted(x["id"] for x in entries(doc) if x.get("parent") and x["parent"] not in ids)
    return [f"{i} is in the backlog file more than once" for i in twice] + [
        f"{i} names a parent that is not in the backlog file" for i in orphans
    ]


def title_of(x: dict) -> str:
    name = PRIVATE_TITLE.format(x["private"]) if x.get("private") else x["title"]
    return f"{x['id']} {name}"


def body_of(x: dict, slices: dict) -> str:
    marker = f"<!-- backlog:{x['id']} -->"
    if x.get("private"):
        return f"{PRIVATE_BODY.format(x['private'])}\n\n{marker}"
    if x["kind"] == "epic":
        return f"Epic. Context: **{x['context']}**.\n\n{marker}"
    if x["kind"] == "feature":
        return f"Feature of {x['parent']}.\n\nSource: {x['source']}\n\n{marker}"
    lines = [x["story"], ""]
    if x.get("criteria"):
        lines += ["### Acceptance criteria", x["criteria"], ""]
    if x.get("needs"):
        lines += [f"**Needs:** {x['needs']}", ""]
    if x.get("replay_pr"):
        lines += [
            f"**Built by:** replay pull request {x['replay_pr']:02d} ({slices[str(x['replay_pr'])]}). "
            "That pull request closes this issue.",
            "",
        ]
    return "\n".join(lines) + marker


def wanted_fields(x: dict) -> dict:
    if x["kind"] in ("epic", "feature"):
        return {"Context": x["context"]}
    wanted = {"Context": x["context"], "Priority": x["priority"], "Release": x["release"], "Replay PR": x["replay_pr"]}
    return {name: value for name, value in wanted.items() if value not in ("", None)}


def same(current, value) -> bool:
    if current is None:
        return False
    if isinstance(value, (int, float)):
        return float(current) == float(value)
    return str(current) == str(value)


class Import:
    def __init__(self, doc: dict, github):
        self.doc = doc
        self.github = github
        self.repo = doc["repo"]
        self.owner = doc["repo"].split("/")[0]
        self.field_kinds = {
            "Context": ("SINGLE_SELECT", [e["context"] for e in doc["epics"]]),
            "Priority": ("SINGLE_SELECT", PRIORITIES),
            "Release": ("TEXT", []),
            "Replay PR": ("NUMBER", []),
        }

    def run(self) -> None:
        found = problems(self.doc)
        if found:
            sys.exit("\n".join(found))
        for name, color in LABELS.items():
            self.github.ensure_label(self.repo, name, color)
        issues = self.sync_issues()
        self.sync_hierarchy(issues)
        self.sync_project(issues)

    def sync_issues(self) -> dict[str, dict | None]:
        issues: dict[str, dict | None] = {}
        for issue in self.github.issues(self.repo):
            marker = MARKER.search(issue["body"])
            if marker:
                issues[marker.group(1)] = issue
        created = updated = 0
        for x in entries(self.doc):
            title, body = title_of(x), body_of(x, self.doc["slices"])
            if x["id"] not in issues:
                issues[x["id"]] = self.github.create_issue(self.repo, title, body, x["kind"])
                created += 1
            elif (issues[x["id"]]["title"], issues[x["id"]]["body"]) != (title, body):
                self.github.update_issue(self.repo, issues[x["id"]]["number"], title, body, x["kind"])
                updated += 1
        print(f"issues: {created} created, {updated} updated, {len(entries(self.doc)) - created - updated} unchanged")
        return issues

    def sync_hierarchy(self, issues: dict[str, dict | None]) -> None:
        parent_of = self.github.parents(self.repo)
        linked = 0
        for x in entries(self.doc):
            if not x.get("parent"):
                continue
            child, parent = issues[x["id"]], issues[x["parent"]]
            if child is None or parent is None:
                print(f"  would put {x['id']} under {x['parent']}")
                linked += 1
                continue
            current = parent_of.get(child["number"])
            if current == parent["number"]:
                continue
            if current:
                sys.exit(
                    f"{x['id']} (issue {child['number']}) is under issue {current}, "
                    f"the backlog file says {x['parent']} (issue {parent['number']})"
                )
            self.github.add_sub_issue(self.repo, parent["number"], child)
            linked += 1
        print(f"hierarchy: {linked} links added")

    def sync_project(self, issues: dict[str, dict | None]) -> None:
        title = self.doc["project"]
        project = self.github.project(self.owner, title) or self.github.create_project(self.owner, title)
        if project is None:
            print(f"project {title}: it does not exist yet, so its fields and items are not compared")
            return
        self.github.link_project(project, self.repo)
        fields = self.sync_fields(project)
        items = self.github.items(project, list(self.field_kinds))
        added = edits = 0
        for x in entries(self.doc):
            issue = issues[x["id"]]
            if issue is None:
                print(f"  would add {x['id']} to the Project with its fields")
                added += 1
                continue
            item = items.get(issue["number"])
            if item is None:
                item = self.github.add_item(project, issue)
                added += 1
            for name, value in wanted_fields(x).items():
                if name not in fields or same((item or {}).get("values", {}).get(name), value):
                    continue
                self.require_option(name, fields[name], value)
                self.github.set_field(project, item, issue, name, fields[name], value)
                edits += 1
        print(f"project {title} (#{project['number']}): {added} items added, {edits} field values set")

    def sync_fields(self, project: dict) -> dict[str, dict]:
        fields = self.github.fields(project)
        if STATUS not in fields:
            sys.exit(f"the Project has no {STATUS} field: it is the Project's own field and this script never makes it")
        missing = [name for name in self.field_kinds if name not in fields]
        for name in missing:
            self.github.create_field(project, name, *self.field_kinds[name])
        return self.github.fields(project) if missing else fields

    @staticmethod
    def require_option(name: str, field: dict, value) -> None:
        if field["options"] and value not in field["options"]:
            sys.exit(f'the Project field {name} has no option "{value}": add it in the Project, then run again')


def roadmap(issues: list[dict]) -> str:
    listed = [
        i
        for i in issues
        if i["priority"] != BUILT and "epic" not in i["labels"] and "feature" not in i["labels"]
    ]
    epics = sorted({i["epic"] or NO_EPIC for i in listed}, key=lambda e: (e == NO_EPIC, natural(e)))
    out = [ROADMAP_HEADER]
    for epic in epics:
        mine = [i for i in listed if (i["epic"] or NO_EPIC) == epic]
        out.append(f"## {epic}\n")
        for priority in priorities_of(mine):
            out.append(f"### {priority}\n")
            rows = [i for i in mine if (i["priority"] or NO_PRIORITY) == priority]
            out += [f"- [{i['title']}]({i['url']})" for i in sorted(rows, key=lambda i: natural(i["title"]))]
            out.append("")
    if not epics:
        out.append("No open story or task.\n")
    return "\n".join(out)


def priorities_of(issues: list[dict]) -> list[str]:
    present = {i["priority"] or NO_PRIORITY for i in issues}
    first = [p for p in ROADMAP_ORDER if p in present]
    rest = sorted(present - set(ROADMAP_ORDER) - {NO_PRIORITY})
    return first + rest + ([NO_PRIORITY] if NO_PRIORITY in present else [])


def pr_stories(pull: dict, issues: list[dict]) -> list[str]:
    branch = re.match(r"replay/(\d+)-", pull["branch"])
    if not branch:
        return [f"the branch {pull['branch']} is not replay/NN-name"]
    number = int(branch.group(1))
    by_number = {i["number"]: i for i in issues}
    expected = {i["number"] for i in issues if i["replay"] == number and "story" in i["labels"]}
    closes = set(pull["closes"])
    print(f"'{pull['title']}' is replay pull request {number:02d}: {len(expected)} stories expected, {len(closes)} closed")
    found = [f"MISSING: Closes #{n}   ({by_number[n]['title']})" for n in sorted(expected - closes)]
    found += [
        f"EXTRA:   #{n} ({by_number[n]['title'] if n in by_number else 'not an issue of this repository'})"
        for n in sorted(closes - expected)
    ]
    if any(word in pull["body"] for word in ATTRIBUTION):
        found.append("FORBIDDEN: the description has an AI attribution line")
    return found


def command_import(args) -> None:
    with open(args.file, encoding="utf-8") as source:
        doc = json.load(source)
    Import(doc, GhCli(write=args.write, pause=args.pause)).run()
    print("done" if args.write else "dry run: nothing was written. Add --write to write to GitHub")


def command_roadmap(args) -> None:
    github = GhCli()
    page = roadmap(github.tracked_issues(args.repo or github.current_repo(), "OPEN"))
    with open(args.output, "w", encoding="utf-8") as out:
        out.write(page)
    print(f"wrote {args.output}")


def command_pr_stories(args) -> None:
    github = GhCli()
    repo = args.repo or github.current_repo()
    found = pr_stories(github.pull_request(repo, args.pull_request), github.tracked_issues(repo, "OPEN,CLOSED"))
    for line in found:
        print(f"  {line}")
    sys.exit(1 if found else 0)


class FakeGitHub:
    def __init__(self):
        self.labels: dict[str, str] = {}
        self.stored: list[dict] = []
        self.parent: dict[int, int] = {}
        self.board: dict | None = None
        self.board_fields: dict[str, dict] = {}
        self.board_items: dict[int, dict] = {}
        self.writes: list[str] = []

    def ensure_label(self, repo, name, color):
        if self.labels.get(name) != color:
            self.labels[name] = color
            self.writes.append(f"label {name}")

    def issues(self, repo):
        return copy.deepcopy(self.stored)

    def create_issue(self, repo, title, body, label):
        number = len(self.stored) + 1
        issue = {"number": number, "id": 1000 + number, "url": f"https://example.test/{number}", "title": title, "body": body}
        self.stored.append(issue)
        self.writes.append(f"create {title}")
        return dict(issue)

    def update_issue(self, repo, number, title, body, label):
        self.stored[number - 1].update(title=title, body=body)
        self.writes.append(f"update {title}")

    def parents(self, repo):
        return {i["number"]: self.parent.get(i["number"]) for i in self.stored}

    def add_sub_issue(self, repo, parent, child):
        self.parent[child["number"]] = parent
        self.writes.append(f"link {child['number']} under {parent}")

    def project(self, owner, title):
        return self.board

    def create_project(self, owner, title):
        self.board = {"number": "1", "id": "P1", "owner": owner}
        self.board_fields = {STATUS: {"id": "F0", "options": {"Todo": "o1", "Done": "o2"}}}
        self.writes.append(f"create project {title}")
        return self.board

    def link_project(self, project, repo):
        pass

    def fields(self, project):
        return copy.deepcopy(self.board_fields)

    def create_field(self, project, name, kind, options):
        self.board_fields[name] = {"id": f"F-{name}", "options": {o: f"o-{o}" for o in options}}
        self.writes.append(f"field {name}")

    def items(self, project, names):
        return copy.deepcopy(self.board_items)

    def add_item(self, project, issue):
        self.board_items[issue["number"]] = {"id": f"I{issue['number']}", "values": {}}
        self.writes.append(f"item {issue['number']}")
        return copy.deepcopy(self.board_items[issue["number"]])

    def set_field(self, project, item, issue, name, field, value):
        self.board_items[issue["number"]]["values"][name] = value
        self.writes.append(f"set {name} of {issue['number']}")


