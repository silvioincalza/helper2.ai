def partial_run_is_finished() -> bool:
    github = FakeGitHub()
    imported(SAMPLE, github)
    whole = list(github.writes)
    half = FakeGitHub()
    half.room = 10
    stopped = stop_of(lambda: imported(SAMPLE, half))
    half.room = None
    imported(SAMPLE, half)
    after = len(half.writes)
    imported(SAMPLE, half)
    once = sorted(half.writes) == sorted(whole) and len(half.writes) == after
    return bool(stopped) and once and half.board_items == github.board_items


