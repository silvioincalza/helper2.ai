class FakeGitHub:
    def __init__(self):
        self.labels: dict[str, str] = {}
        self.stored: list[dict] = []
        self.parent: dict[int, int] = {}
        self.board: dict | None = None
        self.board_fields: dict[str, dict] = {}
        self.board_items: dict[str, dict] = {}
        self.writes: list[str] = []
        self.room: int | None = None
        self.issue_field_list: dict[str, dict] = {
            "Context": {"id": "IF1", "options": {"Checkout": "c1", "Catalog": "c2"}},
            "Priority": {"id": "IF2", "options": {priority: f"p-{priority}" for priority in PRIORITIES}},
            "Release": {"id": "IF3", "options": {}},
        }
        self.issue_field_values: dict[int, dict] = {}
        self.milestone_list: dict[str, int] = {"v2026.11": 1}

    def ensure_label(self, repo, name, color):
        if self.labels.get(name) != color:
            self.labels[name] = color
            self.writes.append(f"label {name}")

    def issues(self, repo):
        return copy.deepcopy(self.stored)

    def create_issue(self, repo, title, body, label):
        number = len(self.stored) + 1
        issue = {
            "number": number,
            "id": 1000 + number,
            "node": f"N{number}",
            "url": f"https://example.test/{number}",
            "title": title,
            "body": body,
            "author": "OWNER",
        }
        self.stored.append(issue)
        self.writes.append(f"create {title}")
        return dict(issue)

    def update_issue(self, repo, number, title, body, label):
        self.stored[number - 1].update(title=title, body=body)
        self.writes.append(f"update {title}")

    def parents(self, repo):
        return {i["number"]: self.parent.get(i["number"]) for i in self.stored}

    def add_sub_issue(self, repo, parent, child):
        self.parent[child["number"]] = parent
        self.writes.append(f"link {child['number']} under {parent}")

    def issue_fields(self, repo):
        return copy.deepcopy(self.issue_field_list)

    def issue_values(self, repo):
        return copy.deepcopy(self.issue_field_values)

    def set_issue_fields(self, edits):
        for edit in edits:
            self.spend()
            values = self.issue_field_values.setdefault(edit["issue"]["number"], {})
            values.update(edit["values"])
            for name in [name for name, value in values.items() if empty(value)]:
                del values[name]
            self.writes.append(f"issue fields of {edit['issue']['number']}")

    def milestones(self, repo):
        return dict(self.milestone_list)

    def set_milestone(self, repo, issue, number, title):
        self.stored[issue["number"] - 1]["milestone"] = title
        self.writes.append(f"milestone of {issue['number']}")

    def project(self, owner, title):
        return self.board

    def create_project(self, owner, title):
        self.board = {"number": "1", "id": "P1", "owner": owner, "repos": []}
        self.board_fields = {STATUS: {"id": "F0", "options": {"Todo": "o1", "Done": "o2"}}}
        self.writes.append(f"create project {title}")
        return self.board

    def link_project(self, project, repo):
        self.board["repos"].append(repo)
        self.writes.append(f"link project to {repo}")

    def fields(self, project):
        return copy.deepcopy(self.board_fields)

    def create_field(self, project, name, kind, options):
        self.board_fields[name] = {"id": f"F-{name}", "options": {o: f"o-{o}" for o in options}}
        self.writes.append(f"field {name}")

    def items(self, project, names):
        return copy.deepcopy(self.board_items)

    def add_items(self, project, issues):
        for issue in issues:
            self.spend()
            self.board_items[issue["url"]] = {"id": f"I{issue['number']}", "values": {}}
            self.writes.append(f"item {issue['number']}")
        return {issue["url"]: copy.deepcopy(self.board_items[issue["url"]]) for issue in issues}

    def set_fields(self, project, edits):
        for edit in edits:
            self.spend()
            values = self.board_items[edit["issue"]["url"]]["values"]
            if empty(edit["value"]):
                del values[edit["name"]]
            else:
                values[edit["name"]] = edit["value"]
            self.writes.append(f"{'clear' if empty(edit['value']) else 'set'} {edit['name']} of {edit['issue']['number']}")

    def spend(self):
        if self.room == 0:
            sys.exit("GitHub's hourly limit is used up")
        if self.room is not None:
            self.room -= 1


