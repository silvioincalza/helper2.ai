#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { canonicalUrl, csrfToken, esc, postJson, resourceId, sleep } from './eval-lib.mjs';

const base = (process.argv.slice(2).find((a) => !a.startsWith('--')) ?? 'http://localhost:8080').replace(/\/$/, '');
const resources = JSON.parse(await readFile(new URL('../docs/eval/setup-resources.json', import.meta.url), 'utf8'));
const OUTPUT = new URL('../docs/evaluation-setup.md', import.meta.url);
const PAUSE_MS = 7000;

async function measure(token, r) {
  const id = resourceId(canonicalUrl(r.url));
  const setupRes = await fetch(`${base}/api/v1/resources/${id}/setup`);
  if (setupRes.status === 404) return { r, missing: true };
  const setup = setupRes.ok ? await setupRes.json() : null;
  const startedAt = Date.now();
  const started = performance.now();
  const guideRes = await postJson(base, token, `/api/v1/resources/${id}/guide`, {});
  const ms = Math.round(performance.now() - started);
  if (!guideRes.ok || !setup) return { r, error: `setup HTTP ${setupRes.status}, guide HTTP ${guideRes.status}` };
  const guide = await guideRes.json();
  const snippets = setup.clients.filter((c) => c.snippets.some((s) => s.supported && s.text)).length;
  return {
    r, ms, setup, guide,
    cached: Date.parse(guide.generatedAt) < startedAt - 1000,
    options: setup.options.length,
    coverage: { clients: setup.clients.length, snippets },
    kept: guide.sections.reduce((n, s) => n + s.steps.length, 0),
    confirmed: guide.sections.reduce((n, s) => n + s.steps.filter((st) => st.text !== null).length, 0),
    sections: guide.sections.filter((s) => s.steps.length).map((s) => `${s.kind} ${s.steps.length}`).join(', '),
    documents: guide.documents.map((d) => d.kind).join(', '),
  };
}

const token = await csrfToken(base);
const rows = [];
for (const [i, r] of resources.entries()) {
  if (i > 0) await sleep(PAUSE_MS);
  const row = await measure(token, r);
  rows.push(row);
  console.log(`${r.id} ${row.missing ? 'not in catalog' : row.error ?? `${row.guide.status} kept ${row.kept} rejected ${row.guide.rejected} ${row.ms}ms`}`);
}

const ok = rows.filter((x) => x.guide);
const count = (status) => ok.filter((x) => x.guide.status === status).length;
const kept = ok.reduce((n, x) => n + x.kept, 0);
const rejected = ok.reduce((n, x) => n + x.guide.rejected, 0);
const confirmed = ok.reduce((n, x) => n + x.confirmed, 0);
const withOptions = ok.filter((x) => x.options > 0);
const covered = withOptions.reduce((n, x) => n + x.coverage.snippets, 0);
const clients = withOptions.reduce((n, x) => n + x.coverage.clients, 0);
const latencies = ok.filter((x) => !x.cached).map((x) => x.ms).sort((a, b) => a - b);
const pct = (p) => (latencies.length ? latencies[Math.min(latencies.length - 1, Math.floor((p / 100) * latencies.length))] : 0);
const failed = rows.filter((x) => x.error);

await writeFile(OUTPUT, `# Setup guide evaluation

Generated by \`scripts/eval-setup.mjs\` on ${new Date().toISOString()} against \`${base}\`.
Resource set: [docs/eval/setup-resources.json](eval/setup-resources.json) (${resources.length} resources fixed before the run).

## Summary

| Metric | Value |
|---|---|
| Resources measured / not in catalog / failed | ${ok.length} / ${rows.filter((x) => x.missing).length} / ${failed.length} |
| Tool guide status OK / NO_STEPS / NO_MATERIAL / LLM_UNAVAILABLE | ${count('OK')} / ${count('NO_STEPS')} / ${count('NO_MATERIAL')} / ${count('LLM_UNAVAILABLE')} |
| Steps kept / rejected by the checks | ${kept} / ${rejected} |
| Kept steps whose text the step check confirmed (the others show only their source) | ${confirmed} / ${kept} |
| Resources with setup options | ${withOptions.length} / ${ok.length} |
| Snippet coverage (clients with a ready snippet / clients, resources with options) | ${covered} / ${clients}${clients ? ` (${Math.round((100 * covered) / clients)} %)` : ''} |
| Tool guide latency p50 / p90 / max (cache hits excluded) | ${pct(50)} ms / ${pct(90)} ms / ${latencies.at(-1) ?? 0} ms |
| Answers from the cache | ${ok.filter((x) => x.cached).length} / ${ok.length} |

## Per resource

| id | kind | status | kept | text confirmed | rejected | sections | documents | options | snippets | latency |
|---|---|---|---|---|---|---|---|---|---|---|
${rows.map((x) => (x.guide
    ? `| ${x.r.id} | ${esc(x.r.kind)} | ${x.guide.status} | ${x.kept} | ${x.confirmed} | ${x.guide.rejected} | ${esc(x.sections || '–')} | ${esc(x.documents || '–')} | ${x.options} | ${x.coverage.snippets} / ${x.coverage.clients} | ${x.ms} ms${x.cached ? ' (cache)' : ''} |`
    : `| ${x.r.id} | ${esc(x.r.kind)} | ${x.missing ? 'not in catalog' : esc(x.error)} | – | – | – | – | – | – | – | – |`)).join('\n')}

## How to read this

- "Kept" are steps whose quote was found in the cited document and whose command is whole lines of one of its code
  blocks; "rejected" are steps the checks removed. A step is kept or rejected by code, never judged by hand.
- "Text confirmed" are kept steps whose AI-written text a second model call found supported by the quote and the
  command; every other kept step shows only its quote and command.
- Snippet coverage counts AI clients that got a ready-to-paste snippet for at least one setup option.
- "Not in catalog": the resource has never been indexed or seen in a search on this backend.
`);
console.log('wrote docs/evaluation-setup.md');
process.exit(failed.length ? 1 : 0);
