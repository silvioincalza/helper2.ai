#!/usr/bin/env node
// Turns a dated events research file (dates read from each event's own site, with the excerpt that states
// them) into a repeatable, idempotent Flyway seed, so no date is typed by hand. One file per set:
//   node scripts/industry-events-seed.mjs docs/research/industry-events-2026-10-27.json industry > backend/src/main/resources/db/migration/R__industry_events.sql
//   node scripts/industry-events-seed.mjs docs/research/community-events-2026-10-27.json community > backend/src/main/resources/db/migration/R__community_events.sql
import { readFileSync } from 'node:fs';

const NS = '6f1c2a8e-4b1d-5c3e-9a7f-2d4e6b8c0a12'; // same UUIDv5 namespace as ai.helper2.shared.ResourceId

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// Several editions share one site (ai.engineer, humanx.co): the edition slug keeps each resource distinct.
// Same rules as ai.helper2.shared.CanonicalUrl: https, host without "www.", no trailing slash. CuratedSeedTest checks it.
const canonical = (u, edition) => {
  const x = new URL(u);
  return `https://${x.hostname.toLowerCase().replace(/^www\./, '')}${x.pathname.replace(/\/+$/, '')}?event=${slug(edition)}`;
};

const KINDS = ['CONFERENCE', 'HACKATHON', 'MEETUP', 'TALK', 'WORKSHOP'];
const FORMATS = ['IN_PERSON', 'ONLINE', 'HYBRID'];
// "industry" (conferences and expos) or "community" (hackathons, meetups, talks, workshops).
const SET = process.argv[3] ?? 'industry';
if (!['industry', 'community'].includes(SET)) throw new Error(`unknown set ${SET}`);
// Marks the source records this seed writes, so removing dropped events never touches another seed's rows.
const FINGERPRINT = `${SET}-events-v1`;
const TAG = `${SET}-event`;

const events = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = [`-- Curated AI ${SET === 'industry' ? 'industry events' : 'community events (hackathons, meetups, talks, workshops)'} for the home page "Next events".
-- GENERATED by scripts/industry-events-seed.mjs from ${process.argv[2]}; edit the research file and regenerate, never this file.
-- Honesty rules: dates are the days each event's own site states, with that excerpt as evidence (an
-- "eventDates" assertion). The place is only what the page states (no country inferred from a city); the
-- format (online, in person, hybrid) only when the page states it, with that excerpt when the file has one.
-- Each excerpt was checked against the live page on 2026-10-27${SET === 'industry' ? ` (CES and Ai4 join two lines with "…";
-- MWC's dates are in the page's structured data)` : ` (one joins two lines with "…"; Meetup.com excerpts
-- come from the page title, the only place those pages state the year)`}. No publication date or price is asserted.
-- Repeatable and idempotent: Flyway re-runs it whenever it changes. Rows are upserted, each event's
-- curated assertions (and their evidence) are replaced, and events no longer in the research file are removed.

INSERT INTO source (id, name, mode, homepage, attribution)
VALUES ('curated', 'Helper2 curated list', 'CURATED', 'https://helper2.ai/sources',
        'Editorial seed written by the Helper2 team; not live data.')
ON CONFLICT (id) DO NOTHING;
`];

for (const e of events) {
  if (!e.startDate || !e.officialUrl || !e.dateExcerpt) throw new Error(`${e.edition}: missing date, URL or excerpt`);
  const canon = canonical(e.officialUrl, e.edition);
  const rid = `uuid_generate_v5('${NS}'::uuid, ${q(canon)})`;
  const start = `${e.startDate}T00:00:00Z`;
  const end = e.endDate ? `${e.endDate}T00:00:00Z` : null;
  const stated = (s) => s && e.dateExcerpt.toLowerCase().includes(s.toLowerCase());
  const location = [e.city, stated(e.country) ? e.country : null].filter(Boolean).join(', ') || null;
  // Industry events are conferences and expos; community events say which kind they are.
  const kind = e.kind ?? (SET === 'industry' ? 'CONFERENCE' : null);
  if (!KINDS.includes(kind)) throw new Error(`${e.edition}: kind must be one of ${KINDS.join(', ')}`);
  const format = e.format ? e.format.toUpperCase().replace(/[\s-]+/g, '_') : null;
  if (format && !FORMATS.includes(format)) throw new Error(`${e.edition}: format must be one of ${FORMATS.join(', ')}`);
  const extra = [`'eventKind', ${q(kind)}`, format ? `'eventFormat', ${q(format)}` : null, location ? `'location', ${q(location)}` : null]
    .filter(Boolean).join(', ');
  out.push(`-- ${e.edition}`);
  out.push(`INSERT INTO resource (id, canonical_url, url, title, description, description_origin, type, audience, data_origin, event_starts_at, event_ends_at)
VALUES (${rid}, ${q(canon)}, ${q(e.officialUrl)}, ${q(e.edition)}, ${q(e.description)}, 'CURATED', 'EVENT', 'BOTH', 'CURATED', ${q(start)}, ${q(end)})
ON CONFLICT (canonical_url) DO UPDATE SET url = EXCLUDED.url, title = EXCLUDED.title, description = EXCLUDED.description,
    description_origin = EXCLUDED.description_origin, type = EXCLUDED.type, audience = EXCLUDED.audience,
    data_origin = EXCLUDED.data_origin, event_starts_at = EXCLUDED.event_starts_at, event_ends_at = EXCLUDED.event_ends_at,
    modified_at = now();`);
  out.push(`DELETE FROM resource_label WHERE resource_id = ${rid};`);
  out.push(`INSERT INTO resource_label (resource_id, kind, value) VALUES (${rid}, 'TAG', ${q(TAG)}) ON CONFLICT DO NOTHING;`);
  out.push(`INSERT INTO source_record (id, source_id, external_id, resource_id, source_url, canonical_url, title, description, type,
                           source_event_starts_at, source_event_ends_at, retrieved_at, fingerprint, extra)
VALUES (gen_random_uuid(), 'curated', ${q(canon)}, ${rid}, ${q(e.dateUrl ?? e.officialUrl)}, ${q(canon)}, ${q(e.edition)}, ${q(e.description)}, 'EVENT',
        ${q(start)}, ${q(end)}, '2026-10-27T00:00:00Z', ${q(FINGERPRINT)},
        jsonb_build_object('descriptionOrigin', 'CURATED', 'audience', 'BOTH', 'useCases', '[]'::jsonb,
                           'tags', ${q(JSON.stringify([TAG]))}::jsonb, 'platforms', '[]'::jsonb, 'popularity', '[]'::jsonb,
                           'publishedPrecision', 'UNKNOWN', 'updatedPrecision', 'UNKNOWN', ${extra}))
ON CONFLICT (source_id, external_id) DO UPDATE SET resource_id = EXCLUDED.resource_id, source_url = EXCLUDED.source_url,
    canonical_url = EXCLUDED.canonical_url, title = EXCLUDED.title, description = EXCLUDED.description, type = EXCLUDED.type,
    source_event_starts_at = EXCLUDED.source_event_starts_at, source_event_ends_at = EXCLUDED.source_event_ends_at,
    retrieved_at = EXCLUDED.retrieved_at, fingerprint = EXCLUDED.fingerprint, extra = EXCLUDED.extra;`);
  out.push(`DELETE FROM evidence WHERE id IN (
    SELECT j.evidence_id FROM field_assertion_evidence j JOIN field_assertion a ON a.id = j.assertion_id
    WHERE a.resource_id = ${rid} AND a.origin = 'CURATED' AND a.enrichment_run_id IS NULL);
DELETE FROM field_assertion WHERE resource_id = ${rid} AND origin = 'CURATED' AND enrichment_run_id IS NULL;`);
  out.push(`WITH a AS (INSERT INTO field_assertion (id, resource_id, field, value, origin, verification)
             VALUES (gen_random_uuid(), ${rid}, 'eventDates', ${q(end ? `${e.startDate}/${e.endDate}` : e.startDate)}, 'CURATED', 'VERIFIED') RETURNING id),
     ev AS (INSERT INTO evidence (id, source_url, retrieved_at, excerpt)
             VALUES (gen_random_uuid(), ${q(e.dateUrl ?? e.officialUrl)}, '2026-10-27T00:00:00Z', ${q(e.dateExcerpt.slice(0, 500))}) RETURNING id)
INSERT INTO field_assertion_evidence (assertion_id, evidence_id) SELECT a.id, ev.id FROM a, ev;
`);
  if (format && e.formatExcerpt) {
    out.push(`WITH a AS (INSERT INTO field_assertion (id, resource_id, field, value, origin, verification)
             VALUES (gen_random_uuid(), ${rid}, 'eventFormat', ${q(format)}, 'CURATED', 'VERIFIED') RETURNING id),
     ev AS (INSERT INTO evidence (id, source_url, retrieved_at, excerpt)
             VALUES (gen_random_uuid(), ${q(e.dateUrl ?? e.officialUrl)}, '2026-10-27T00:00:00Z', ${q(e.formatExcerpt.slice(0, 500))}) RETURNING id)
INSERT INTO field_assertion_evidence (assertion_id, evidence_id) SELECT a.id, ev.id FROM a, ev;
`);
  }
}

// Events dropped from the research file: only resources whose curated record this seed wrote. Their curated
// evidence goes first (it is not tied to a source record), then the record; the resource goes with its last record.
const listed = events.map((e) => q(canonical(e.officialUrl, e.edition))).join(',\n    ');
out.push(`-- Events no longer in the research file
CREATE TEMPORARY TABLE dropped_event ON COMMIT DROP AS
SELECT resource_id, external_id FROM source_record
WHERE source_id = 'curated' AND fingerprint = ${q(FINGERPRINT)} AND external_id NOT IN (
    ${listed});
DELETE FROM evidence WHERE id IN (
    SELECT j.evidence_id FROM field_assertion_evidence j JOIN field_assertion a ON a.id = j.assertion_id
    JOIN dropped_event d ON d.resource_id = a.resource_id
    WHERE a.origin = 'CURATED' AND a.enrichment_run_id IS NULL);
DELETE FROM field_assertion a USING dropped_event d
WHERE a.resource_id = d.resource_id AND a.origin = 'CURATED' AND a.enrichment_run_id IS NULL;
DELETE FROM source_record s USING dropped_event d WHERE s.source_id = 'curated' AND s.external_id = d.external_id;
DELETE FROM resource r USING dropped_event d
WHERE r.id = d.resource_id AND r.data_origin = 'CURATED' AND NOT EXISTS (SELECT 1 FROM source_record o WHERE o.resource_id = r.id);
`);

process.stdout.write(out.join('\n'));
