#!/usr/bin/env node
// Turns the dated model-family research file (every fact with URL + verbatim excerpt, read from the
// provider's own pages) into a repeatable, idempotent Flyway seed, so no spec is typed by hand.
//   node scripts/model-families-seed.mjs docs/research/model-families-2026-10-27.json > backend/src/main/resources/db/migration/R__model_families.sql
import { readFileSync } from 'node:fs';

const NS = '6f1c2a8e-4b1d-5c3e-9a7f-2d4e6b8c0a12'; // same UUIDv5 namespace as ai.helper2.shared.ResourceId

// Family id (matches Compatibility tool ids) and the tags Scout sources put on that provider's models:
// hf-provider-orgs adds the Hub organisation (lower-cased).
const FAMILIES = {
  OpenAI: { id: 'openai', tags: ['openai'] },
  Anthropic: { id: 'anthropic', tags: [] },
  Google: { id: 'google', tags: ['google'] },
  xAI: { id: 'xai', tags: ['xai-org'] },
  Meta: { id: 'meta', tags: ['meta-llama'] },
  'Mistral AI': { id: 'mistral', tags: ['mistralai'] },
  DeepSeek: { id: 'deepseek', tags: ['deepseek-ai'] },
  Alibaba: { id: 'qwen', tags: ['qwen'] },
  NVIDIA: { id: 'nvidia', tags: ['nvidia'] },
};

// Research field name -> assertion field (the API's spec keys).
const FIELDS = {
  contextWindow: 'contextTokens',
  maxOutputTokens: 'maxOutputTokens',
  inputPricePerMTokUsd: 'inputUsdPerMTok',
  outputPricePerMTokUsd: 'outputUsdPerMTok',
  inputModalities: 'inputModalities',
  outputModalities: 'outputModalities',
  openWeights: 'openWeights',
  license: 'license',
  knowledgeCutoff: 'knowledgeCutoff',
  releaseDate: 'released',
};

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const clip = (s, n) => (s && s.length > n ? `${s.slice(0, n - 1)}…` : s);
const val = (v) => (Array.isArray(v) ? v.join(',') : String(v));

// Same rules as ai.helper2.shared.CanonicalUrl for these simple URLs: https, lower-case host without
// "www.", no fragment, no trailing slash. CuratedSeedTest checks every seed URL is already canonical.
const canonical = (u) => {
  const x = new URL(u);
  return `https://${x.hostname.toLowerCase().replace(/^www\./, '')}${x.pathname.replace(/\/+$/, '')}${x.search}`;
};

// Curated specs of one resource are replaced as a whole: their evidence first (the join rows cascade), then
// the assertions. AI-extracted assertions and anything tied to an enrichment run are never touched.
const replaceCuratedAssertions = (rid) => `DELETE FROM evidence WHERE id IN (
    SELECT j.evidence_id FROM field_assertion_evidence j JOIN field_assertion a ON a.id = j.assertion_id
    WHERE a.resource_id = ${rid} AND a.origin = 'CURATED' AND a.enrichment_run_id IS NULL);
DELETE FROM field_assertion WHERE resource_id = ${rid} AND origin = 'CURATED' AND enrichment_run_id IS NULL;`;

const data = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const families = Array.isArray(data) ? data : data.families;
const out = [];
out.push(`-- AI model families for the comparison page. GENERATED by scripts/model-families-seed.mjs from
-- ${process.argv[2]} — edit the research file and regenerate, never this file.
-- Repeatable and idempotent: Flyway re-runs it whenever it changes. Rows are upserted; each family's curated
-- assertions (and their evidence) are replaced, and families no longer in the research file are removed.
-- Honesty rules: every spec is a CURATED assertion with the provider page it was read from, a verbatim
-- excerpt and the read date. A field no official page stated is absent (shown as "Not stated").

INSERT INTO source (id, name, mode, homepage, attribution)
VALUES ('curated', 'Helper2 curated list', 'CURATED', 'https://helper2.ai/sources',
        'Editorial seed written by the Helper2 team; not live data.')
ON CONFLICT (id) DO NOTHING;
`);

families.forEach((f, i) => {
  const fam = FAMILIES[f.provider];
  if (!fam) throw new Error(`unknown provider ${f.provider}`);
  if (!f.modelsPageUrl) throw new Error(`${f.provider}: no verified models page`);
  const url = f.modelsPageUrl;
  const canon = canonical(url);
  const rid = `uuid_generate_v5('${NS}'::uuid, ${q(canon)})`;
  // "OpenAI GPT", "Meta Llama"; a provider whose family carries its own name is just that name.
  const name = f.provider === 'Alibaba' ? 'Qwen' : f.provider.startsWith(f.family) ? f.family : `${f.provider} ${f.family}`;
  const retrieved = `${f.retrievedAt ?? '2026-10-27'}T00:00:00Z`;
  const ow = f.fields?.openWeights?.value;
  out.push(`-- ${name}`);
  out.push(`INSERT INTO resource (id, canonical_url, url, title, description, description_origin, type, audience, tech_level, data_origin)
VALUES (${rid}, ${q(canon)}, ${q(url)}, ${q(name)}, ${q(f.description)}, 'CURATED', 'MODEL', 'BOTH', 'INTERMEDIATE', 'CURATED')
ON CONFLICT (canonical_url) DO UPDATE SET url = EXCLUDED.url, title = EXCLUDED.title, description = EXCLUDED.description,
    description_origin = EXCLUDED.description_origin, type = EXCLUDED.type, audience = EXCLUDED.audience,
    tech_level = EXCLUDED.tech_level, data_origin = EXCLUDED.data_origin, modified_at = now();`);
  out.push(`DELETE FROM resource_label WHERE resource_id = ${rid};`);
  out.push(`INSERT INTO resource_label (resource_id, kind, value) VALUES (${rid}, 'TAG', 'model-family') ON CONFLICT DO NOTHING;`);
  out.push(`INSERT INTO source_record (id, source_id, external_id, resource_id, source_url, canonical_url, title, description, type, retrieved_at, fingerprint, extra)
VALUES (gen_random_uuid(), 'curated', ${q(canon)}, ${rid}, ${q(url)}, ${q(canon)}, ${q(name)}, ${q(f.description)}, 'MODEL', ${q(retrieved)}, 'model-families-v1',
        jsonb_build_object('descriptionOrigin', 'CURATED', 'audience', 'BOTH', 'techLevel', 'INTERMEDIATE', 'useCases', '[]'::jsonb,
                           'tags', '["model-family"]'::jsonb, 'platforms', '["api"]'::jsonb, 'popularity', '[]'::jsonb,
                           'publishedPrecision', 'UNKNOWN', 'updatedPrecision', 'UNKNOWN'))
ON CONFLICT (source_id, external_id) DO UPDATE SET resource_id = EXCLUDED.resource_id, source_url = EXCLUDED.source_url,
    canonical_url = EXCLUDED.canonical_url, title = EXCLUDED.title, description = EXCLUDED.description, type = EXCLUDED.type,
    retrieved_at = EXCLUDED.retrieved_at, fingerprint = EXCLUDED.fingerprint, extra = EXCLUDED.extra;`);
  out.push(`INSERT INTO model_family (id, position, provider, name, open_weights, resource_id, provider_tags)
VALUES (${q(fam.id)}, ${i}, ${q(f.provider)}, ${q(name)}, ${typeof ow === 'boolean' ? ow : 'NULL'}, ${rid}, ${fam.tags.length ? `ARRAY[${fam.tags.map(q).join(', ')}]` : `'{}'::text[]`})
ON CONFLICT (id) DO UPDATE SET position = EXCLUDED.position, provider = EXCLUDED.provider, name = EXCLUDED.name,
    open_weights = EXCLUDED.open_weights, resource_id = EXCLUDED.resource_id, provider_tags = EXCLUDED.provider_tags;`);
  out.push(replaceCuratedAssertions(rid));

  const facts = [];
  if (f.flagship?.name) {
    const basis = f.flagship.basis ?? f.flagship;
    facts.push({ field: 'flagship', value: f.flagship.apiId ? `${f.flagship.name} (${f.flagship.apiId})` : f.flagship.name, url: basis.url ?? url, excerpt: basis.excerpt ?? null });
  }
  for (const [k, field] of Object.entries(FIELDS)) {
    const v = f.fields?.[k];
    if (v && v.value !== null && v.value !== undefined && v.url) facts.push({ field, value: val(v.value), url: v.url, excerpt: v.excerpt ?? null });
  }
  for (const b of f.benchmarks ?? []) {
    b.name ??= b.benchmark;
    if (b.name && b.score !== null && b.score !== undefined && b.url) facts.push({ field: `benchmark:${b.name}`, value: String(b.score).replace('%', ''), url: b.url, excerpt: b.excerpt ?? null });
  }
  for (const fact of facts) {
    out.push(`WITH a AS (INSERT INTO field_assertion (id, resource_id, field, value, origin, verification)
             VALUES (gen_random_uuid(), ${rid}, ${q(fact.field)}, ${q(fact.value)}, 'CURATED', 'VERIFIED') RETURNING id),
     e AS (INSERT INTO evidence (id, source_url, retrieved_at, excerpt)
             VALUES (gen_random_uuid(), ${q(fact.url)}, ${q(retrieved)}, ${q(clip(fact.excerpt, 500))}) RETURNING id)
INSERT INTO field_assertion_evidence (assertion_id, evidence_id) SELECT a.id, e.id FROM a, e;`);
  }
  out.push('');
});

out.push(`DELETE FROM model_family WHERE id NOT IN (${families.map((f) => q(FAMILIES[f.provider].id)).join(', ')});`);
out.push('');

process.stdout.write(out.join('\n'));
